export const hz = (midi) => 440 * 2 ** ((midi - 69) / 12);
export function eventFor(track, step) {
  const chord = track.chords[Math.floor(step / 16) % track.chords.length];
  const rhythm = ["dialtone", "sodium", "cassette"].includes(track.id);
  const percussion = !rhythm
    ? null
    : step % 8 === 0
      ? "kick"
      : step % 8 === 4
        ? "snare"
        : step % 2 === 1
          ? "hat"
          : null;
  return {
    bass: step % 4 === 0 ? track.root + chord : null,
    lead:
      track.melody[step % track.melody.length] === null
        ? null
        : track.root + track.melody[step % track.melody.length],
    chord:
      step % 16 === 0
        ? [
            track.root + chord + 12,
            track.root + chord + (track.id === "paper" ? 16 : 15),
            track.root + chord + 19,
          ]
        : [],
    percussion,
  };
}
